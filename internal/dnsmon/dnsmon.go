// Package dnsmon configures CoreDNS to behave like a disconnected site's DNS
// and parses the queries it logs.
package dnsmon

import (
	"net/netip"
	"regexp"
	"strings"
	"time"
)

const logTag = "gapdrill-dns"

// Corefile returns a CoreDNS configuration for an offline cluster. Names in
// the cluster domain resolve as usual. Every other name gets NXDOMAIN, as at
// a disconnected site, and each such query is logged with the client's IP.
//
// The two zones live in separate server blocks on purpose: CoreDNS runs
// plugins in a fixed compile-time order in which "template" comes before
// "kubernetes", so a catch-all template in the same block would also answer
// cluster names.
func Corefile() string {
	return `# Generated by gapdrill: names outside the cluster get NXDOMAIN, like a disconnected site.
cluster.local:53 in-addr.arpa:53 ip6.arpa:53 {
    errors
    kubernetes cluster.local in-addr.arpa ip6.arpa {
        pods insecure
        fallthrough in-addr.arpa ip6.arpa
        ttl 30
    }
    cache 30
    loadbalance
}
.:53 {
    errors
    health {
        lameduck 5s
    }
    ready
    prometheus :9153
    log . "` + logTag + ` {remote} {type} {name} {rcode}"
    template ANY ANY {
        rcode NXDOMAIN
    }
}
`
}

// Query is one query for an outside name.
type Query struct {
	Time   time.Time
	Client netip.Addr
	Type   string
	// Name has no trailing dot.
	Name  string
	RCode string
}

var lineRE = regexp.MustCompile(logTag + ` (\S+) (\S+) (\S+) (\S+)\s*$`)

// ParseLine parses one line of CoreDNS output, as streamed with
// PodLogOptions.Timestamps (an RFC 3339 timestamp, a space, then the line).
// It returns false for lines that aren't gapdrill query logs.
func ParseLine(line string) (Query, bool) {
	ts, rest, ok := strings.Cut(line, " ")
	if !ok {
		return Query{}, false
	}
	t, err := time.Parse(time.RFC3339Nano, ts)
	if err != nil {
		return Query{}, false
	}
	m := lineRE.FindStringSubmatch(rest)
	if m == nil {
		return Query{}, false
	}
	client, err := netip.ParseAddr(strings.Trim(m[1], "[]"))
	if err != nil {
		return Query{}, false
	}
	return Query{Time: t, Client: client, Type: m[2], Name: strings.TrimSuffix(m[3], "."), RCode: m[4]}, true
}

// DropSearchExpansions removes names that are only a resolver's search-domain
// expansion of another name in the list: when both "pypi.org" and
// "pypi.org.corp.example" appear and "corp.example" is a search domain, the
// latter is dropped. Order is preserved.
func DropSearchExpansions(names, searchDomains []string) []string {
	present := make(map[string]bool, len(names))
	for _, n := range names {
		present[n] = true
	}
	var out []string
	for _, n := range names {
		expansion := false
		for _, sd := range searchDomains {
			sd = strings.Trim(sd, ".")
			if base, ok := strings.CutSuffix(n, "."+sd); ok && sd != "" && present[base] {
				expansion = true
				break
			}
		}
		if !expansion {
			out = append(out, n)
		}
	}
	return out
}
