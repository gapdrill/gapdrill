package mirror

import (
	"fmt"
	"sort"
)

// HostsDir is where kind nodes read registry host configuration. gapdrill's
// cluster config sets containerd's config_path to it.
const HostsDir = "/etc/containerd/certs.d"

const header = `# Generated by gapdrill. Every pull is served by the drill's bundle registry.
# "server" points there too: containerd falls back to "server" after trying
# the hosts, so nothing ever reaches the upstream registry.
`

// HostsFiles returns containerd hosts.toml files, keyed by path relative to
// HostsDir, that send every image pull to the bundle registry at addr
// (host:port, reachable from the nodes).
//
// Each bundle registry gets a host entry whose path keeps the upstream
// registry name (see Image.MirrorRepository). Registries outside the bundle
// fall through to "_default", which also points at the bundle registry, so
// their pulls fail with "not found" instead of reaching the internet.
func HostsFiles(addr string, registries []string) map[string]string {
	files := map[string]string{
		"_default/hosts.toml": header + fmt.Sprintf("server = %q\n", "http://"+addr),
	}
	seen := map[string]bool{}
	sorted := append([]string(nil), registries...)
	sort.Strings(sorted)
	for _, r := range sorted {
		if seen[r] {
			continue
		}
		seen[r] = true
		files[r+"/hosts.toml"] = header + fmt.Sprintf(`server = %q

[host.%q]
  capabilities = ["pull", "resolve"]
  override_path = true
`, "http://"+addr, "http://"+addr+"/v2/"+MirrorPrefix(r))
	}
	return files
}
